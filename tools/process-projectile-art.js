// Single generated effect frames -> transparent three-frame projectile atlases.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createCanvas, loadImage } from '@napi-rs/canvas';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'assets/sprite-art');
const config = JSON.parse(fs.readFileSync(path.join(SRC, 'projectiles.json'), 'utf8'));
const manifest = {};
for (const [type, spec] of Object.entries(config)) {
  const canvas = createCanvas(96 * 3, 96),
    g = canvas.getContext('2d');
  g.imageSmoothingEnabled = false;
  const rects = [];
  for (let frame = 0; frame < 3; frame++) {
    const image = await loadImage(path.join(SRC, 'projectiles', type, frame + '.png'));
    const source = createCanvas(image.width, image.height),
      sg = source.getContext('2d');
    sg.drawImage(image, 0, 0);
    const data = sg.getImageData(0, 0, image.width, image.height),
      d = data.data;
    let left = image.width,
      top = image.height,
      right = -1,
      bottom = -1;
    for (let y = 0; y < image.height; y++)
      for (let x = 0; x < image.width; x++) {
        const i = (y * image.width + x) * 4;
        if (d[i + 3] < 128) {
          d[i + 3] = 0;
          continue;
        }
        d[i + 3] = 255;
        left = Math.min(left, x);
        right = Math.max(right, x);
        top = Math.min(top, y);
        bottom = Math.max(bottom, y);
      }
    if (right < left) throw new Error('Empty projectile: ' + type + '/' + frame);
    sg.putImageData(data, 0, 0);
    const sw = right - left + 1,
      sh = bottom - top + 1;
    const phaseScale = type === 'boom' ? [0.65, 1, 0.85][frame] : 1;
    const scale = Math.min((spec.size[0] * 2) / sw, (spec.size[1] * 2) / sh) * phaseScale;
    const w = Math.max(1, Math.round(sw * scale)),
      h = Math.max(1, Math.round(sh * scale));
    const x = frame * 96 + Math.floor((96 - w) / 2),
      y = Math.floor((96 - h) / 2);
    g.drawImage(source, left, top, sw, sh, x, y, w, h);
    rects.push([x, y, w, h]);
  }
  fs.writeFileSync(
    path.join(ROOT, 'public/atlases', 'projectile-' + type + '.png'),
    canvas.toBuffer('image/png'),
  );
  manifest[type] = { frames: 3, rects };
  console.log(type + ': 3 frames');
}
fs.writeFileSync(
  path.join(ROOT, 'src/game/data/projectile-art.js'),
  '/* Generated by tools/process-projectile-art.js. */\nconst PROJECTILE_ART = ' +
    JSON.stringify(manifest, null, 2) +
    ';\nexport { PROJECTILE_ART };\n',
);
