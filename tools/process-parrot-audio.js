/** Edit the supplied originals without changing their pitch. Requires ffmpeg/ffprobe. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
const [byd] = process.argv.slice(2);
if (!byd) throw new Error('Usage: node tools/process-parrot-audio.js <byd.mp3>');
const out = 'public/audio/memes';
fs.mkdirSync(out, { recursive: true });
const clips = {};
for (const id of ['parrot-byd-full']) {
  const source = byd;
  const file = id + '.mp3';
  const filters = [
    'highpass=f=90',
    'lowpass=f=10000',
    'afade=t=in:d=0.018',
    'areverse',
    'afade=t=in:d=0.09',
    'areverse',
    'loudnorm=I=-18:TP=-2:LRA=7',
    'alimiter=limit=0.794:level=false',
  ].join(',');
  execFileSync('ffmpeg', [
    '-nostdin',
    '-y',
    '-v',
    'error',
    '-i',
    source,
    '-vn',
    '-af',
    filters,
    '-ar',
    '44100',
    '-ac',
    '1',
    '-c:a',
    'libmp3lame',
    '-b:a',
    '128k',
    '-map_metadata',
    '-1',
    path.join(out, file),
  ]);
  const duration = Number(
    execFileSync(
      'ffprobe',
      ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path.join(out, file)],
      { encoding: 'utf8' },
    ),
  );
  clips[id] = {
    file,
    duration,
    completeSource: true,
    source: path.basename(source),
    sourceSha256: crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex'),
  };
}
fs.writeFileSync(
  path.join(out, 'edits.json'),
  JSON.stringify(
    {
      loudness: '-18 LUFS',
      peak: '-2 dBTP',
      processing: 'Complete original at native speed; EQ, edge fades, normalization, limiter',
      clips,
    },
    null,
    2,
  ) + '\n',
);
const runtime = Object.fromEntries(
  Object.entries(clips).map(([id, clip]) => [
    id,
    { file: clip.file, frames: Math.ceil(clip.duration * 60) + 12 },
  ]),
);
fs.writeFileSync(
  'src/game/data/parrot-memes.js',
  '/* Generated by tools/process-parrot-audio.js. */\nexport const PARROT_MEMES = ' +
    JSON.stringify(runtime, null, 2) +
    ';\n',
);
for (const obsolete of [
  'parrot-byd-1.mp3',
  'parrot-byd-2.mp3',
  'parrot-byd-3.mp3',
  'parrot-byd.mp3',
  'parrot-byd-reaction.mp3',
  'parrot-milkshake.mp3',
]) {
  const file = path.join(out, obsolete);
  if (fs.existsSync(file)) fs.unlinkSync(file);
}
console.log(clips);
