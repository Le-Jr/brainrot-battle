"""Sprite sheet -> game atlas pipeline for Brainrot Battaglia.

Input : assets/sprite-sheets/<id>.png  (4x3 grid, 12 poses, transparent background)
Output: public/atlases/<id>.png          (one horizontal atlas per character, served by Next)
        src/game/data/atlas-frames.js    (12 frames per character: [x, y, w, h, anchorX, anchorY])
Usage : npm run sprites   (or: python3 tools/process_sprites.py)
Requires: pillow, numpy, scipy
"""
from PIL import Image
import numpy as np, json
from scipy import ndimage
import os,sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D=os.path.join(ROOT,'assets','sprite-sheets')+os.sep
OUTDIR=os.path.join(ROOT,'public','atlases')
FRAMES=os.path.join(ROOT,'src','game','data','atlas-frames.js')
SHEETS={'chimp':('chimp.png',124),'tralalero':('tralalero.png',None),'tung':('tung.png',126),'ballerina':('ballerina.png',124),'bombardiro':('bombardiro.png',None),'lirili':('lirili.png',132),'assassino':('assassino.png',118),'patapim':('patapim.png',128),'saturnita':('saturnita.png',None)}
WIDE={'saturnita':150,'bombardiro':150,'tralalero':136}
OUT={}
OUTC=(27,16,36)
def frames_of(im,it=2):
    a=im[:,:,3]>128
    lab,n=ndimage.label(ndimage.binary_dilation(a,iterations=it) if it>0 else a)
    idx=np.arange(1,n+1);areas=ndimage.sum(np.ones_like(lab),lab,idx);objs=ndimage.find_objects(lab)
    big=[k for k in range(n) if areas[k]>8000]
    owner={k:k for k in big}
    cen=lambda s_:((s_[0].start+s_[0].stop)/2,(s_[1].start+s_[1].stop)/2)
    for k in range(n):
        if k in owner or areas[k]<30: continue
        cy,cx=cen(objs[k]);best=min(big,key=lambda b:max(0,objs[b][0].start-cy,cy-objs[b][0].stop)+max(0,objs[b][1].start-cx,cx-objs[b][1].stop))
        owner[k]=best
    frames=[]
    for b in big:
        ks=[k+1 for k,o in owner.items() if o==b];mask=np.isin(lab,ks)&a
        ys,xs=np.nonzero(mask);frames.append((ys.min(),ys.max()+1,xs.min(),xs.max()+1,mask))
    frames.sort(key=lambda f:((f[0]+f[1])//2//341,f[2]))
    return frames
for name,(f,target) in SHEETS.items():
    im=np.array(Image.open(D+f).convert('RGBA'))
    boxes=frames_of(im,2)
    if len(boxes)!=12: boxes=frames_of(im,1)
    if len(boxes)!=12: boxes=frames_of(im,0) if True else boxes
    print(name,len(boxes));assert len(boxes)==12,(name,len(boxes))
    crops=[]
    for (y0,y1,x0,x1,mask) in boxes:
        c=im[y0:y1,x0:x1].copy();c[:,:,3]=np.where(mask[y0:y1,x0:x1],255,0)
        ys,xs=np.nonzero(c[:,:,3]);c=c[ys.min():ys.max()+1,xs.min():xs.max()+1]
        crops.append(c)
    idle=crops[0]
    if name in WIDE: s=WIDE[name]/idle.shape[1]
    else: s=target/idle.shape[0]
    frames=[]
    for i,c in enumerate(crops):
        img=Image.fromarray(c,'RGBA');w=max(1,round(c.shape[1]*s));h=max(1,round(c.shape[0]*s))
        r=np.array(img.resize((w,h),Image.LANCZOS)).astype(np.int32)
        al=r[:,:,3]>110
        rgb=np.clip(r[:,:,:3],0,255).astype(np.uint8)
        # outline 1px
        pad=np.zeros((h+2,w+2,4),np.uint8);pad[1:-1,1:-1,:3]=rgb;pad[1:-1,1:-1,3]=np.where(al,255,0)
        A=pad[:,:,3]>0
        ring=ndimage.binary_dilation(A)&~A
        pad[ring]=[*OUTC,255]
        frames.append(pad)
    # quantize all frames together to shared palette
    W=sum(f.shape[1] for f in frames)+2*len(frames);Hh=max(f.shape[0] for f in frames)
    atlas=np.zeros((Hh,W,4),np.uint8);meta=[];x=0
    for i,fr in enumerate(frames):
        h,w=fr.shape[:2];atlas[:h,x:x+w]=fr
        # anchor: bottom baseline; x anchor computed later
        meta.append([x,0,w,h]);x+=w+2
    rgbimg=Image.fromarray(atlas[:,:,:3]);q=rgbimg.quantize(64,method=Image.MEDIANCUT,dither=Image.Dither.NONE).convert('RGB')
    atlas[:,:,:3]=np.array(q)
    # anchors
    def bbox(fr):
        ys,xs=np.nonzero(fr[:,:,3]);return xs.min(),xs.max()
    il,ir=bbox(frames[0]);ic=(il+ir)/2
    t0=frames[0][:int(frames[0].shape[0]*.32),:,3];_,xs0=np.nonzero(t0);itc=(xs0.min()+xs0.max())/2
    anch=[]
    for i,fr in enumerate(frames):
        l,r=bbox(fr);h=fr.shape[0]
        top=fr[:max(2,int(h*.32)),:,3];ys,xs=np.nonzero(top);tc=(xs.min()+xs.max())/2
        if i==11: ax=(l+r)/2
        elif name in WIDE: ax=(r-(ir-ic)) if i==10 else l+(ic-il)
        elif i in (5,6,7): ax=l+(ic-il)
        else: ax=tc+(ic-itc)
        anch.append([round(ax),h-1])
    for m,a in zip(meta,anch): m+=a
    out=os.path.join(OUTDIR,name+'.png');Image.fromarray(atlas,'RGBA').save(out,'PNG',optimize=True)
    OUT[name]=meta
    print(name,'scale',round(s,3),'atlas',atlas.shape,'bytes',os.path.getsize(out))
lines=['/* Generated by tools/process_sprites.py. Per character: 12 frames as [x, y, w, h, anchorX, anchorY] in its atlas PNG. */','const ATLAS_FRAMES={']
lines+=['  %s:%s,'%(k,json.dumps(v,separators=(',',':'))) for k,v in OUT.items()]
lines+=['};','','export { ATLAS_FRAMES };','']
open(FRAMES,'w',encoding='utf-8').write('\n'.join(lines))
open(os.path.join(ROOT,'src','game','data','atlas-animations.js'),'w',encoding='utf-8').write('/* Legacy 12-pose atlas mapping. */\nconst ATLAS_ANIMATIONS = {};\nexport { ATLAS_ANIMATIONS };\n')
print('wrote',FRAMES)
