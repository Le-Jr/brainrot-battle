"""Import user-provided music with measured, constant loudness gain and bounded peaks.
Originals are read-only. A short equal-power overlap joins the end to the beginning.
"""
import argparse,hashlib,json,subprocess
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'public/audio/music'
WORK=ROOT/'output/music/import'
SOURCES=[
 ('title','Quarter_In_The_Slot.mp3','Quarter In The Slot'),
 ('select','Last_Token_Remaining.mp3','Last Token Remaining'),
 ('beach','Saltwater_Standoff.mp3','Saltwater Standoff'),
 ('cafe-alt','Cold_Coffee_and_Keys.mp3','Cold Coffee and Keys'),
 ('sahur','Village_Standoff.mp3','Village Standoff'),
 ('cafe','Café Duel.mp3','Café Duel'),
 ('jungle','Iron_Grip_Standoff.mp3','Iron Grip Standoff'),
 ('desert',"Scorpion's Claw.mp3","Scorpion’s Claw"),
 ('ascension','The Ominant Signal.mp3','The Ominant Signal'),
 ('laststand','Toccata of the Final Battle.mp3','Toccata of the Final Battle'),
 ('piazza','Brawl_in_the_Piazza.mp3','Brawl in the Piazza'),
 ('beach-alt','Boardwalk_Brawl.mp3','Boardwalk Brawl'),
 ('byd','Favela_Knockout.mp3','Favela Knockout'),
 ('cyber','Asphalt_Impact.mp3','Asphalt Impact'),
 ('bonus','Throttle_Lock.mp3','Throttle Lock'),
 ('boss','Cathedral_of_the_Unbeaten.mp3','Cathedral of the Unbeaten'),
 ('ending','The_Last_Quarter.mp3','The Last Quarter'),
 ('win','Winner_s_Stance.mp3',"Winner's Stance"),
 ('cont','Ten_Seconds_Remaining.mp3','Ten Seconds Remaining'),
]

def run(args):
 return subprocess.run(args,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)

def measure(file):
 r=run(['ffmpeg','-hide_banner','-nostats','-i',str(file),'-af','loudnorm=I=-20:TP=-3:LRA=11:print_format=json','-f','null','-'])
 text=r.stderr.decode();return json.JSONDecoder().raw_decode(text[text.rfind('{'):])[0]

def main():
 OUT.mkdir(parents=True,exist_ok=True);WORK.mkdir(parents=True,exist_ok=True)
 parser=argparse.ArgumentParser()
 parser.add_argument('--only',nargs='+',choices=[row[0] for row in SOURCES])
 args=parser.parse_args()
 report_path=OUT/'import-report.json'
 catalog=json.loads(report_path.read_text()) if args.only and report_path.exists() else {}
 for key,filename,title in SOURCES:
  if args.only and key not in args.only: continue
  src=Path('/home/gandalf/Downloads')/filename
  digest=hashlib.sha256(src.read_bytes()).hexdigest()[:10]
  intermediate=WORK/(key+'-loop.wav')
  duration=float(json.loads(run(['ffprobe','-v','error','-show_entries','format=duration','-of','json',str(src)]).stdout)['format']['duration'])
  # Tail -> head crossfade is placed at the end; playback starts one second into the source.
  overlap=0.05 if key=='title' else 1.0
  graph=(f'[0:a]aresample=44100,asplit=3[main][tail][head];'
   f'[main]atrim=start={overlap}:end={duration-overlap},asetpts=PTS-STARTPTS[body];'
   f'[tail]atrim=start={duration-overlap},asetpts=PTS-STARTPTS[t];'
   f'[head]atrim=end={overlap},asetpts=PTS-STARTPTS[h];'
   f'[t][h]acrossfade=d={overlap}:c1=qsin:c2=qsin[seam];'
   '[body][seam]concat=n=2:v=0:a=1[out]')
  # Victory is a one-shot cue: preserve its opening and natural ending.
  if key=='win':
   overlap=0.0
   graph='[0:a]aresample=44100[out]'
  run(['ffmpeg','-y','-v','error','-i',str(src),'-filter_complex',graph,'-map','[out]','-ac','2','-c:a','pcm_s24le',str(intermediate)])
  before=measure(intermediate)
  # Static gain preserves the dynamics; choose the quieter gain if true peak needs headroom.
  gain=min(-20-float(before['input_i']),-3-float(before['input_tp']))
  target=OUT/f'imported-{key}-{digest}.ogg'
  run(['ffmpeg','-y','-v','error','-i',str(intermediate),'-af',f'volume={gain}dB','-ar','44100','-ac','2','-c:a','libvorbis','-q:a','5','-metadata',f'title={title}',str(target)])
  after=measure(target)
  actual=float(json.loads(run(['ffprobe','-v','error','-show_entries','format=duration','-of','json',str(target)]).stdout)['format']['duration'])
  assert float(after['input_tp']) < -1, f'{key}: true peak too high'
  assert float(after['input_i']) <= -19.5, f'{key}: loudness too high'
  catalog[key]={'title':title,'url':'/audio/music/'+target.name,'source':filename,'sourceHash':digest,'duration':actual,'loudness':float(after['input_i']),'truePeak':float(after['input_tp']),'gainDb':round(gain,2),'overlapSeconds':overlap,'alternative':key.endswith('-alt')}
  print(f'{key}: {actual:.1f}s / {after["input_i"]} LUFS / {after["input_tp"]} dBTP',flush=True)
 (ROOT/'src/game/audio/imported-music.js').write_text('/** User-provided tracks, normalized locally. Generated by tools/import-music.py. */\nexport const IMPORTED_MUSIC = '+json.dumps(catalog,ensure_ascii=False,indent=2)+';\n')
 (OUT/'import-report.json').write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n')

if __name__=='__main__':main()
