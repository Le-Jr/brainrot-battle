import fs from 'node:fs';
import { createCanvas, loadImage } from '@napi-rs/canvas';

const sizes = { nonno: [88, 40], cyber: [96, 46], byd: [88, 40], parrot: [32, 36] };
const metadata = {};
const preview = createCanvas(1000, 320),
  pg = preview.getContext('2d');
pg.fillStyle = '#32283f';
pg.fillRect(0, 0, 1000, 320);
let row = 0;
for (const [id, [width, height]] of Object.entries(sizes)) {
  const sheet = createCanvas(256 * 5, 208),
    g = sheet.getContext('2d');
  g.imageSmoothingEnabled = false;
  for (let frame = 0; frame < 5; frame++) {
    const image = await loadImage(`assets/bonus-art/${id}-${frame}.png`);
    const source = createCanvas(image.width, image.height),
      sg = source.getContext('2d');
    sg.drawImage(image, 0, 0);
    const pixels = sg.getImageData(0, 0, image.width, image.height);
    let l = image.width,
      r = -1,
      t = image.height,
      b = -1;
    for (let y = 0; y < image.height; y++)
      for (let x = 0; x < image.width; x++) {
        const i = (y * image.width + x) * 4;
        if (pixels.data[i + 3] < 128) {
          pixels.data[i + 3] = 0;
          continue;
        }
        pixels.data[i + 3] = 255;
        l = Math.min(l, x);
        r = Math.max(r, x);
        t = Math.min(t, y);
        b = Math.max(b, y);
      }
    if (r < l) throw new Error('Empty bonus frame: ' + id + frame);
    sg.putImageData(pixels, 0, 0);
    const h = height * 2 * (id === 'parrot' ? 1 : frame === 4 ? 0.5 : frame === 3 ? 0.85 : 1);
    const scale = Math.min((width * 2) / (r - l + 1), h / (b - t + 1));
    const dw = Math.round((r - l + 1) * scale),
      dh = Math.round((b - t + 1) * scale);
    g.drawImage(source, l, t, r - l + 1, b - t + 1, frame * 256 + 128 - Math.floor(dw / 2), 200 - dh, dw, dh);
  }
  fs.writeFileSync(`public/atlases/bonus-${id}.png`, sheet.toBuffer('image/png'));
  metadata[id === 'nonno' ? 'car' : id] = { file: `bonus-${id}.png`, frames: 5 };
  pg.fillStyle = '#fff';
  pg.fillText(id, 4, row * 80 + 12);
  pg.imageSmoothingEnabled = false;
  for (let i = 0; i < 5; i++)
    pg.drawImage(sheet, i * 256, 0, 256, 208, i * 200 + 30, row * 80 - 24, 128, 104);
  row++;
}
fs.writeFileSync(
  'src/game/data/bonus-art.js',
  '/* Generated by tools/process-bonus-art.js */\nexport const BONUS_ART = ' +
    JSON.stringify(metadata, null, 2) +
    ';\n',
);
fs.mkdirSync('output/bonus-art', { recursive: true });
fs.writeFileSync('output/bonus-art/preview.png', preview.toBuffer('image/png'));
console.log('3 cars × 5 damage states; parrot × 5 poses.');
