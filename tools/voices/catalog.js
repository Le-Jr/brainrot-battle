import { ASCENSION, FINAL_VICTORY } from '../../src/game/story/finale.js';
import fs from 'node:fs';
import crypto from 'node:crypto';
import { HYPE } from '../../src/game/audio/announcer.js';
import { ELON_LINES } from '../../src/game/audio/elon-lines.js';
import { voiceKey } from '../../src/game/audio/voice-key.js';
import { CH, PLAYABLE } from '../../src/game/characters/roster.js';
import { BOSS } from '../../src/game/characters/fighters/saturnita.js';
import { STORY } from '../../src/game/story/character-arcs.js';
import { WORLD_PRO, CALL_PANEL, BOSS_DEFEAT, EPILOGUE } from '../../src/game/story/world.js';
import { preFight, freedScene, bossIntro } from '../../src/game/story/encounters.js';
import { LOC } from '../../src/game/world/map.js';
import { S } from '../../src/game/state.js';

const lines = new Map(),
  clips = {};
function add(text, role = 'pt', speaker = role, exaggeration = 0.5) {
  const key = voiceKey(text, role);
  if (lines.has(key)) return lines.get(key).file;
  const file = crypto.createHash('sha256').update(key).digest('hex').slice(0, 16) + '.mp3';
  const line = { key, text, language: role === 'ann' ? 'en' : role, speaker, exaggeration, file };
  lines.set(key, line);
  clips[key] = [file];
  return file;
}
function panel(p, me, opp) {
  const speaker = p.sp === 'P' ? me?.id : p.sp === 'O' ? opp?.id : p.sp === 'B' ? BOSS.id : 'narrator';
  add(p.tx.replace(/"/g, ''), 'pt', speaker || 'narrator', p.fx === 'shake' ? 0.75 : 0.5);
}
for (const text of Object.values(HYPE).flat()) add(text, 'ann', 'announcer', 0.75);
for (const text of [
  'Continue?',
  'Game over...',
  "Let's go!",
  'Level up!',
  'Bonus stage!',
  'Random!',
  'brainrot battaglia!',
  'Tupinicode... presents!',
  'Round one... Fight!',
])
  add(text, 'ann', 'announcer', 0.7);
add('Um jogo de Leandro Junior');
add('Muito além da internet existe Brainrotália.');
add('Campione del Brainrot!', 'it', 'announcer', 0.7);
const fighters = [...PLAYABLE, BOSS];
for (const ch of fighters) {
  add(ch.voice, 'it', ch.id, 0.7);
  add(ch.call || ch.voice, 'it', ch.id, 0.8);
  add(ch.voice.replace(/!$/, '') + '... vince!', 'it', 'announcer', 0.75);
}
const versus = add('contro', 'it', 'announcer');
for (const a of fighters)
  for (const b of fighters)
    clips[voiceKey(a.voice.replace(/!$/, '') + '... contro... ' + b.voice, 'it')] = [
      add(a.voice, 'it', a.id),
      versus,
      add(b.voice, 'it', b.id),
    ];
for (const loc of LOC) {
  add('Próxima parada: ' + loc.say);
  add(loc.n.toLowerCase(), 'it', 'announcer');
}
for (const place of ['NEON CITTÀ', 'VILA BRASILINI']) add(place.toLowerCase(), 'it', 'announcer');
for (const text of [
  'MILK SHAKE DE MORANGO... É MUITO CREMOSO!',
  'NÓOOO! MEU BI-AI-DI!',
  'NÃÃÃO... ERA ZERO KM!',
])
  add(text, 'pt', 'parrot', 0.85);
add('MAMMA MIA! LA MIA MACCHINA!', 'it', 'nonno', 0.85);
ELON_LINES.forEach((line, i) => add(line.text, i === 0 ? 'ann' : 'pt', 'elon', 0.5 + i * 0.1));
for (const p of [...ASCENSION, ...FINAL_VICTORY])
  add(p.text, 'pt', p.voice, p.voice === 'saturnita' ? 0.8 : 0.65);
for (const p of [...WORLD_PRO, CALL_PANEL, ...BOSS_DEFEAT, ...EPILOGUE]) panel(p);
for (let i = 0; i < PLAYABLE.length; i++) {
  const me = PLAYABLE[i];
  S.p1 = i;
  for (const p of [...STORY[me.id].pro, ...STORY[me.id].end, ...bossIntro()]) panel(p, me);
  for (const opp of CH)
    if (opp !== me) {
      for (let li = 0; li < 7; li++) for (const p of preFight(me, opp, li)) panel(p, me, opp);
      for (let n = 1; n <= 7; n++) for (const p of freedScene(me, opp, n)) panel(p, me, opp);
    }
}
S.p1 = 0;
fs.mkdirSync('output/voices', { recursive: true });
fs.writeFileSync('output/voices/catalog.json', JSON.stringify([...lines.values()], null, 2) + '\n');
fs.writeFileSync(
  'src/game/data/voice-clips.js',
  '/* Generated by tools/voices/catalog.js. */\nexport const VOICE_CLIPS = ' +
    JSON.stringify(clips, null, 2) +
    ';\n',
);
console.log(`${lines.size} unique clips, ${Object.keys(clips).length} dialogue entries (VS reuses names).`);
