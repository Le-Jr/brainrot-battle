/* Music data: note parsing, bass patterns and the 21 tracks played by the synth. */
const NOTE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
function noteMidi(s) {
  const m = /^([A-G])([#b]?)(\d)$/.exec(s);
  if (!m) return null;
  return 12 * (+m[3] + 1) + NOTE[m[1]] + (m[2] === '#' ? 1 : m[2] === 'b' ? -1 : 0);
}
const mf = (m) => 440 * Math.pow(2, (m - 69) / 12);
function chordInfo(s) {
  const m = /^([A-G])([#b]?)(m?)/.exec(s);
  const pc = NOTE[m[1]] + (m[2] === '#' ? 1 : m[2] === 'b' ? -1 : 0);
  return { pc: (pc + 12) % 12, tones: m[3] ? [0, 3, 7, 12] : [0, 4, 7, 12], minor: !!m[3] };
}
